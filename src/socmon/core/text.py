"""Нормализация распознанной речи.

Один слой на всю систему: и грамматики узлов, и офлайн-кодирование должны
видеть одинаково нормализованный текст, иначе онлайн- и офлайн-проход начнут
расходиться на пустом месте.
"""

from __future__ import annotations

import re
import unicodedata

_PUNCT = re.compile(r"[^\w\s-]", flags=re.UNICODE)
_SPACES = re.compile(r"\s+")
_WORD = re.compile(r"[\w-]+", flags=re.UNICODE)

#: Числительные 0-10 в формах, реально встречающихся в телефонном ответе.
#: Шкалы ТЗ §7.2 — числовые, и это самое частое место ошибок распознавания.
NUMERALS: dict[str, int] = {
    "ноль": 0, "нуль": 0, "нолик": 0,
    "один": 1, "одна": 1, "одно": 1, "единица": 1, "единицу": 1, "раз": 1,
    "два": 2, "две": 2, "двойка": 2, "двойку": 2,
    "три": 3, "тройка": 3, "тройку": 3,
    "четыре": 4, "четверка": 4, "четверку": 4,
    "пять": 5, "пятерка": 5, "пятерку": 5,
    "шесть": 6, "шестерка": 6, "шестерку": 6,
    "семь": 7, "семерка": 7, "семерку": 7,
    "восемь": 8, "восьмерка": 8, "восьмерку": 8,
    "девять": 9, "девятка": 9, "девятку": 9,
    "десять": 10, "десятка": 10, "десятку": 10,
}

#: Простые числительные второго десятка. Отдельно, потому что составными
#: они не бывают: «одиннадцать» — одно слово, а не «десять один».
TEENS: dict[str, int] = {
    "одиннадцать": 11, "двенадцать": 12, "тринадцать": 13, "четырнадцать": 14,
    "пятнадцать": 15, "шестнадцать": 16, "семнадцать": 17, "восемнадцать": 18,
    "девятнадцать": 19,
}

#: Десятки. Нужны для возраста: шкала 0-10 обходилась единицами, а «сколько
#: вам полных лет» без них не разбирается вовсе.
TENS: dict[str, int] = {
    "двадцать": 20, "тридцать": 30, "сорок": 40, "пятьдесят": 50,
    "шестьдесят": 60, "семьдесят": 70, "восемьдесят": 80, "девяносто": 90,
}

#: Единицы для составных числительных: «сорок» + «пять».
UNITS: dict[str, int] = {
    "один": 1, "два": 2, "три": 3, "четыре": 4, "пять": 5,
    "шесть": 6, "семь": 7, "восемь": 8, "девять": 9,
}

NUMERALS.update(TEENS)
NUMERALS.update(TENS)


def normalize(text: str) -> str:
    """Привести реплику к каноническому виду: регистр вниз, ё→е,
    пунктуация в пробелы.

    Композиция строго NFKC. Разложение (NFKD) со срезанием комбинирующих
    знаков здесь недопустимо: «й» разбирается на «и» + бреве, и «пожалуйста»
    превращается в «пожалуиста». Из русских букв особого обращения требует
    только «ё» — её схлопываем с «е» явной заменой.
    """
    lowered = text.lower().replace("ё", "е")
    composed = unicodedata.normalize("NFKC", lowered)
    without_punct = _PUNCT.sub(" ", composed)
    return _SPACES.sub(" ", without_punct).strip()


def tokenize(text: str) -> list[str]:
    """Токены уже нормализованного текста."""
    return _WORD.findall(text)


def parse_number(text: str, low: int, high: int) -> int | None:
    """Достать из реплики единственное число в диапазоне [low, high].

    Возвращает None, если чисел нет или их несколько разных: «то ли семь,
    то ли восемь» — это не ответ, а повод переспросить.
    """
    tokens = tokenize(normalize(text))
    found: list[int] = []
    position = 0
    while position < len(tokens):
        token = tokens[position]
        if token.isdigit():
            found.append(int(token))
        elif token in TENS:
            # Составное числительное: «сорок пять» — одно число, а не два.
            # Без склейки оно попадало бы в found дважды и отбраковывалось
            # правилом «нескольких разных чисел».
            following = tokens[position + 1] if position + 1 < len(tokens) else ""
            unit = UNITS.get(following)
            if unit is not None:
                found.append(TENS[token] + unit)
                position += 2
                continue
            found.append(TENS[token])
        elif token in NUMERALS:
            found.append(NUMERALS[token])
        position += 1
    in_range = [n for n in found if low <= n <= high]
    if not in_range:
        return None
    if len(set(in_range)) > 1:
        return None
    return in_range[0]
